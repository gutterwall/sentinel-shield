<?php
/**
 * Generates docs/SETTINGS.md from SettingsSchema, so the written reference
 * always matches the settings form and the Documentation tab. (readme.txt keeps
 * to WordPress.org's length limits and points here.)
 *
 * Usage: php bin/settings-docs.php [--write|--check]
 *   (no option) print the file
 *   --write     write docs/SETTINGS.md
 *   --check     exit 1 if docs/SETTINGS.md is out of date (used by bin/build.sh and CI)
 *
 * Runs without WordPress: translation functions are stubbed to return the English text.
 *
 * @package SentinelShield
 */

// phpcs:disable -- Developer tool, not shipped in the plugin zip.

define( 'ABSPATH', __DIR__ . '/' );
define( 'SENTINEL_SHIELD_VERSION', 'dev' );

function __( $text, $domain = '' ) {
	return $text;
}

spl_autoload_register(
	static function ( $class_name ) {
		$prefix = 'SentinelShield\\';
		if ( 0 === strncmp( $class_name, $prefix, strlen( $prefix ) ) ) {
			require dirname( __DIR__ ) . '/src/' . str_replace( '\\', '/', substr( $class_name, strlen( $prefix ) ) ) . '.php';
		}
	}
);

use SentinelShield\Admin\DocsTab;
use SentinelShield\Admin\View;
use SentinelShield\Settings;
use SentinelShield\SettingsSchema;

$defaults = Settings::defaults();
$fields   = SettingsSchema::fields();
$out      = array(
	'# Settings reference',
	'',
	'<!-- Generated by bin/settings-docs.php from src/SettingsSchema.php. Do not edit; run: php bin/settings-docs.php --write -->',
	'',
	'Every setting on Sentinel Shield → Settings, with its key (as used by `wp sentinel settings-get` / `settings-set` and exported settings files), default and recommended value. The same reference, with live values, is on Settings → Documentation in the plugin.',
	'',
	'Malware Lockdown measures are not affected by test mode: once switched on, they are enforced.',
	'',
);
foreach ( SettingsSchema::tabs() as $tab => $title ) {
	$mine = array_filter( $fields, static fn( array $f ): bool => $f['tab'] === $tab );
	if ( ! $mine ) {
		continue;
	}
	$out[] = "## Settings → $title";
	$out[] = '';
	foreach ( $mine as $field ) {
		$rec   = View::recommended_text( $field );
		$meta  = array( '`' . $field['key'] . '`', 'default: ' . DocsTab::value_text( $field, Settings::get_path( $defaults, (string) $field['key'] ) ) );
		$meta[] = 'recommended: ' . ( '' === $rec ? 'your choice' : $rec );
		if ( in_array( $field['key'], Settings::OVERRIDABLE, true ) ) {
			$meta[] = 'per-site on multisite';
		}
		$line = '* **' . $field['label'] . '** (' . implode( '; ', $meta ) . ').';
		if ( 'select' === $field['type'] ) {
			$line .= ' Choices: ' . implode( '; ', array_map( static fn( $label ): string => '"' . $label . '"', $field['options'] ) ) . '.';
		} elseif ( 'number' === $field['type'] ) {
			$line .= ' Range ' . $field['min'] . '–' . $field['max'] . '.';
		}
		$out[] = $line . ' ' . $field['help'];
	}
	$out[] = '';
}
array_push(
	$out,
	'## wp-config.php constants',
	'',
	"* `define( 'SENTINEL_SHIELD_DISABLE', true );` Emergency switch: Sentinel Shield loads nothing. Use it to get back in, fix the cause, then remove the line.",
	"* `define( 'SENTINEL_SHIELD_ADMINS', 'admin#1, jane#7' );` Fixes the approved administrator list in this file and always enforces the administrator lock. See [ADMINISTRATORS.md](ADMINISTRATORS.md).",
	"* `define( 'SENTINEL_SHIELD_DATA_DIR', '/srv/private/sentinel-shield' );` The private folder for the early firewall snapshot, its block log and the server blocklist files. Must be outside the web root and writable by PHP. Default: `sentinel-shield-data` next to the WordPress folder.",
	"* `define( 'DISALLOW_FILE_EDIT', true );` WordPress's own file editor switch. Stronger than the lockdown setting because it lives in a file instead of the database.",
	"* `define( 'DISABLE_WP_CRON', true );` Only with a real server cron job (the line is shown on the Scheduled Tasks page); otherwise blocklist updates and the malware scan stop.",
	'',
	'## Filters',
	'',
	'* `sentinel_shield_allowed_chain_hosts` (array of host names): blockchain gateways a legitimate plugin may still reach while "Block blockchain command channels" is on.',
	'* `sentinel_shield_data_dir` (string): the private folder, when `SENTINEL_SHIELD_DATA_DIR` is not defined.',
	''
);
$doc = implode( "\n", $out );

$mode = $argv[1] ?? '';
if ( '' === $mode ) {
	echo $doc;
	exit( 0 );
}
$file = dirname( __DIR__ ) . '/docs/SETTINGS.md';
if ( '--check' === $mode ) {
	if ( ! is_file( $file ) || file_get_contents( $file ) !== $doc ) {
		fwrite( STDERR, "docs/SETTINGS.md is out of date. Run: php bin/settings-docs.php --write\n" );
		exit( 1 );
	}
	exit( 0 );
}
file_put_contents( $file, $doc );
echo "docs/SETTINGS.md updated.\n";
