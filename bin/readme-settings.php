<?php
/**
 * Generates the "Settings reference" section of readme.txt from SettingsSchema,
 * so the readme always matches the settings form and the Documentation tab.
 *
 * Usage: php bin/readme-settings.php [--write|--check]
 *   (no option) print the section
 *   --write     replace the section in readme.txt
 *   --check     exit 1 if readme.txt is out of date (used by bin/build.sh)
 *
 * Runs without WordPress: translation functions are stubbed to return the English text.
 *
 * @package SentinelShield
 */

// phpcs:disable -- Developer tool, not shipped in the plugin zip.

define( 'ABSPATH', __DIR__ . '/' );
define( 'SENTINEL_SHIELD_VERSION', 'dev' );

function __( $text, $domain = '' ) {
	return $text;
}

spl_autoload_register(
	static function ( $class_name ) {
		$prefix = 'SentinelShield\\';
		if ( 0 === strncmp( $class_name, $prefix, strlen( $prefix ) ) ) {
			require dirname( __DIR__ ) . '/src/' . str_replace( '\\', '/', substr( $class_name, strlen( $prefix ) ) ) . '.php';
		}
	}
);

use SentinelShield\Admin\DocsTab;
use SentinelShield\Admin\View;
use SentinelShield\Settings;
use SentinelShield\SettingsSchema;

const START = '<!-- settings-reference:start (generated by bin/readme-settings.php; edit src/SettingsSchema.php instead) -->';
const END   = '<!-- settings-reference:end -->';

$defaults = Settings::defaults();
$fields   = SettingsSchema::fields();
$out      = array( START, '' );
foreach ( SettingsSchema::tabs() as $tab => $title ) {
	$mine = array_filter( $fields, static fn( array $f ): bool => $f['tab'] === $tab );
	if ( ! $mine ) {
		continue;
	}
	$out[] = "= Settings → $title =";
	$out[] = '';
	foreach ( $mine as $field ) {
		$rec   = View::recommended_text( $field );
		$meta  = array( '`' . $field['key'] . '`', 'default: ' . DocsTab::value_text( $field, Settings::get_path( $defaults, (string) $field['key'] ) ) );
		$meta[] = 'recommended: ' . ( '' === $rec ? 'your choice' : $rec );
		if ( in_array( $field['key'], Settings::OVERRIDABLE, true ) ) {
			$meta[] = 'per-site on multisite';
		}
		$line = '* **' . $field['label'] . '** (' . implode( '; ', $meta ) . ').';
		if ( 'select' === $field['type'] ) {
			$line .= ' Choices: ' . implode( '; ', array_map( static fn( $label ): string => '"' . $label . '"', $field['options'] ) ) . '.';
		} elseif ( 'number' === $field['type'] ) {
			$line .= ' Range ' . $field['min'] . '–' . $field['max'] . '.';
		}
		$out[] = $line . ' ' . $field['help'];
	}
	$out[] = '';
}
$out[]   = END;
$section = implode( "\n", $out );

$mode = $argv[1] ?? '';
if ( '' === $mode ) {
	echo $section, "\n";
	exit( 0 );
}
$file   = dirname( __DIR__ ) . '/readme.txt';
$readme = (string) file_get_contents( $file );
$start  = strpos( $readme, START );
$end    = strpos( $readme, END );
if ( false === $start || false === $end ) {
	fwrite( STDERR, "readme.txt has no settings-reference markers.\n" );
	exit( 2 );
}
$updated = substr( $readme, 0, $start ) . $section . substr( $readme, $end + strlen( END ) );
if ( '--check' === $mode ) {
	if ( $updated !== $readme ) {
		fwrite( STDERR, "readme.txt settings reference is out of date. Run: php bin/readme-settings.php --write\n" );
		exit( 1 );
	}
	exit( 0 );
}
file_put_contents( $file, $updated );
echo "readme.txt updated.\n";
